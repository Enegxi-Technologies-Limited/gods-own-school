// Builds per-page metadata with a canonical URL and matching social share fields.
// openGraph and twitter are replaced (not merged) per route, so the shared fields are repeated here.
export function pageMetadata({ title, description, path }) {
  const fullTitle = `${title} | ${site.name}`;
  return {
    title,
    description,
    alternates: { canonical: path },
    openGraph: {
      title: fullTitle,
      description,
      url: path,
      siteName: site.name,
      locale: "en_NG",
      type: "website",
      images: [shareImage],
    },
    twitter: {
      card: "summary_large_image",
      title: fullTitle,
      description,
      images: [shareImage],
    },
  };
}
